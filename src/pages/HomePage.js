/*
 * STEP 05Z — image-feature freehand brush
 *
 * Source logo reference:
 * 189 × 126 px.
 *
 * The centerlines below are derived from the two dominant ribbon/check
 * trajectories in the logo silhouette. They intentionally do NOT close
 * into circles: each stroke descends into a valley, then accelerates
 * upward. The final polygon is generated by perfect-freehand.
 */

