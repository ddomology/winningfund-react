function clamp01(value) {
  return Math.max(0, Math.min(1, value))
}

function easeOutCubic(value) {
  const t = clamp01(value)
  return 1 - ((1 - t) ** 3)
}

function catmullRomPoint(p0, p1, p2, p3, t) {
  const t2 = t * t
  const t3 = t2 * t

  return [
    0.5
      * (
        (2 * p1[0])
        + (-p0[0] + p2[0]) * t
        + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2
        + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3
      ),
    0.5
      * (
        (2 * p1[1])
        + (-p0[1] + p2[1]) * t
        + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2
        + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3
      ),
  ]
}

function sampleCatmullRom(anchorPoints, samplesPerSegment = 10) {
  if (anchorPoints.length < 2) {
    return anchorPoints
  }

  const sampled = []

  for (let index = 0; index < anchorPoints.length - 1; index += 1) {
    const p0 = anchorPoints[Math.max(0, index - 1)]
    const p1 = anchorPoints[index]
    const p2 = anchorPoints[index + 1]
    const p3 = anchorPoints[Math.min(anchorPoints.length - 1, index + 2)]

    for (let sampleIndex = 0; sampleIndex < samplesPerSegment; sampleIndex += 1) {
      const t = sampleIndex / samplesPerSegment
      sampled.push(catmullRomPoint(p0, p1, p2, p3, t))
    }
  }

  sampled.push(anchorPoints[anchorPoints.length - 1])

  return sampled
}

function pressureForCheckA(t) {
  if (t < 0.12) {
    return 0.30 + (0.72 - 0.30) * (t / 0.12)
  }

  if (t < 0.48) {
    return 0.72 + (0.94 - 0.72) * ((t - 0.12) / 0.36)
  }

  if (t < 0.70) {
    return 0.94 + (0.72 - 0.94) * ((t - 0.48) / 0.22)
  }

  return 0.72 + (0.16 - 0.72) * ((t - 0.70) / 0.30)
}

function pressureForCheckB(t) {
  if (t < 0.12) {
    return 0.26 + (0.80 - 0.26) * (t / 0.12)
  }

  if (t < 0.44) {
    return 0.80 + (1.00 - 0.80) * ((t - 0.12) / 0.32)
  }

  if (t < 0.68) {
    return 1.00 + (0.70 - 1.00) * ((t - 0.44) / 0.24)
  }

  return 0.70 + (0.08 - 0.70) * ((t - 0.68) / 0.32)
}

function withPressure(centerline, pressureProfile) {
  const lastIndex = Math.max(1, centerline.length - 1)

  return centerline.map(([x, y], index) => [
    x,
    y,
    pressureProfile(index / lastIndex),
  ])
}

function getSvgPathFromStroke(stroke) {
  if (!stroke.length) {
    return ''
  }

  const rounded = stroke.map(([x, y]) => [
    Number(x.toFixed(2)),
    Number(y.toFixed(2)),
  ])

  const first = rounded[0]
  const parts = [`M ${first[0]} ${first[1]} Q`]

  for (let index = 0; index < rounded.length; index += 1) {
    const current = rounded[index]
    const next = rounded[(index + 1) % rounded.length]

    parts.push(
      `${current[0]} ${current[1]} `
      + `${((current[0] + next[0]) / 2).toFixed(2)} `
      + `${((current[1] + next[1]) / 2).toFixed(2)}`,
    )
  }

  parts.push('Z')
  return parts.join(' ')
}

function buildFreehandPath(points, visibleProgress, size) {
  const progress = clamp01(visibleProgress)

  if (progress <= 0 || points.length < 2) {
    return ''
  }

  const count = Math.max(
    2,
    Math.min(
      points.length,
      Math.ceil(points.length * progress),
    ),
  )

  const partialPoints = points.slice(0, count)

  const stroke = getStroke(partialPoints, {
    size,
    thinning: 0.68,
    smoothing: 0.78,
    streamline: 0.34,
    simulatePressure: false,
    start: {
      taper: 10,
      cap: true,
    },
    end: {
      taper: progress >= 0.999 ? 34 : 3,
      cap: false,
    },
  })

  return getSvgPathFromStroke(stroke)
}

function useReducedMotion() {
  const [reducedMotion, setReducedMotion] = useState(false)

  useEffect(() => {
    const mediaQuery = window.matchMedia(
      '(prefers-reduced-motion: reduce)',
    )

    const sync = () => setReducedMotion(mediaQuery.matches)
    sync()

    mediaQuery.addEventListener?.('change', sync)

    return () => {
      mediaQuery.removeEventListener?.('change', sync)
    }
  }, [])

  return reducedMotion
}

function WinningFundSloganBrush() {
  const reducedMotion = useReducedMotion()

  const checkAPoints = useMemo(
    () => withPressure(
      sampleCatmullRom(WF_LOGO_FEATURES.checkA, 10),
      pressureForCheckA,
    ),
    [],
  )

  const checkBPoints = useMemo(
    () => withPressure(
      sampleCatmullRom(WF_LOGO_FEATURES.checkB, 11),
      pressureForCheckB,
    ),
    [],
  )

  const [paths, setPaths] = useState(() => ({
    checkA: '',
    checkB: '',
  }))

  useEffect(() => {
    if (reducedMotion) {
      setPaths({
        checkA: buildFreehandPath(checkAPoints, 1, 34),
        checkB: buildFreehandPath(checkBPoints, 1, 38),
      })
      return undefined
    }

    let frameId = 0
    const startedAt = performance.now()

    const checkAStart = 1340
    const checkADuration = 760
    const checkBStart = 1700
    const checkBDuration = 920

    const draw = (now) => {
      const elapsed = now - startedAt

      const checkAProgress = easeOutCubic(
        (elapsed - checkAStart) / checkADuration,
      )

      const checkBProgress = easeOutCubic(
        (elapsed - checkBStart) / checkBDuration,
      )

      setPaths({
        checkA: buildFreehandPath(
          checkAPoints,
          checkAProgress,
          34,
        ),
        checkB: buildFreehandPath(
          checkBPoints,
          checkBProgress,
          38,
        ),
      })

      if (checkAProgress < 1 || checkBProgress < 1) {
        frameId = requestAnimationFrame(draw)
      }
    }

    frameId = requestAnimationFrame(draw)

    return () => {
      cancelAnimationFrame(frameId)
    }
  }, [
    checkAPoints,
    checkBPoints,
    reducedMotion,
  ])

  return createElement(
    'svg',
    {
      className: 'wf-home-kinetic-slogan__brush',
      viewBox:
        `0 0 ${WF_BRUSH_VIEWBOX.width} ${WF_BRUSH_VIEWBOX.height}`,
      preserveAspectRatio: 'none',
      'aria-hidden': 'true',
      focusable: 'false',
    },
    createElement(
      'defs',
      null,
      createElement(
        'linearGradient',
        {
          id: 'wf-slogan-brush-gradient-a',
          gradientUnits: 'userSpaceOnUse',
          x1: '34',
          y1: '108',
          x2: '250',
          y2: '42',
        },
        createElement('stop', {
          offset: '0%',
          stopColor: '#89E2FA',
        }),
        createElement('stop', {
          offset: '48%',
          stopColor: '#69CCF5',
        }),
        createElement('stop', {
          offset: '78%',
          stopColor: '#269DEB',
        }),
        createElement('stop', {
          offset: '100%',
          stopColor: '#0079FA',
        }),
      ),
      createElement(
        'linearGradient',
        {
          id: 'wf-slogan-brush-gradient-b',
          gradientUnits: 'userSpaceOnUse',
          x1: '205',
          y1: '112',
          x2: '398',
          y2: '8',
        },
        createElement('stop', {
          offset: '0%',
          stopColor: '#69CCF5',
        }),
        createElement('stop', {
          offset: '42%',
          stopColor: '#269DEB',
        }),
        createElement('stop', {
          offset: '72%',
          stopColor: '#0079FA',
        }),
        createElement('stop', {
          offset: '100%',
          stopColor: '#1034DC',
        }),
      ),
      createElement(
        'filter',
        {
          id: 'wf-slogan-brush-rough',
          x: '-10%',
          y: '-22%',
          width: '120%',
          height: '144%',
          colorInterpolationFilters: 'sRGB',
        },
        createElement('feTurbulence', {
          type: 'fractalNoise',
          baseFrequency: '0.012 0.18',
          numOctaves: '2',
          seed: '17',
          result: 'brushNoise',
        }),
        createElement('feDisplacementMap', {
          in: 'SourceGraphic',
          in2: 'brushNoise',
          scale: '2.1',
          xChannelSelector: 'R',
          yChannelSelector: 'G',
        }),
      ),
    ),
    createElement('path', {
      className:
        'wf-home-kinetic-slogan__check wf-home-kinetic-slogan__check--1',
      d: paths.checkA,
      fill: 'url(#wf-slogan-brush-gradient-a)',
      filter: 'url(#wf-slogan-brush-rough)',
    }),
    createElement('path', {
      className:
        'wf-home-kinetic-slogan__check wf-home-kinetic-slogan__check--2',
      d: paths.checkB,
      fill: 'url(#wf-slogan-brush-gradient-b)',
      filter: 'url(#wf-slogan-brush-rough)',
    }),
  )
}

